"""Направление «лучше» у показателя: больше — лучше (выручка, NPS, доля решённых в срок) или меньше — лучше (время
ответа, срок, затраты, ошибки, отток, жалобы). От него зависит, кто «выполнил план» и кто «не уложился в цель»:
у времени решения факт 1,8 ч при цели 2 ч — цель выполнена, а 9,6 ч при цели 6 ч — нет (жюри 20.10: вывод был
перевёрнут — «План выполнили 3 из 4», хотя уложилась в SLA только Первая линия).

Источники — по силе: слова автора о цели («не более 2 часов», «меньше — лучше», «целевое ≤ 6 ч»; «не менее 80%»,
«больше — лучше»; «уложиться в SLA» направления не говорит — у доступности уложиться значит «не ниже»), имя колонки цели («Максимум, ч», «Лимит затрат», «Не менее, %»), смысл
самой величины (её имя и единица: длительность, ошибки, затраты…). Ничего не сказано — больше — лучше.

Модуль работает только со строками (имя, единица, текст), без `Data`: его же зовёт самопроверка
(`verstka/data/verify.py`), которая не смотрит на виды анализа."""

from __future__ import annotations

import re
from typing import Optional

__all__ = ["text_direction", "target_direction", "name_direction", "lower_better", "DIRECTION_SOURCES"]

# откуда взято направление: слова автора, колонка цели, смысл величины, по умолчанию
DIRECTION_SOURCES = ("brief", "target", "name", "default")

# ── слова автора ──────────────────────────────────────────────────────────────────────────────────────────────────────
_TEXT_LOWER = re.compile(
    r"меньше\s*[—–-]?\s*лучше|чем\s+меньше\b[^.;!?]{0,60}?\bтем\s+лучше|"
    r"(?<![а-яё])не\s+(?:более|больше|выше|дольше|позже|позднее|длиннее|дороже|превыша\w*)(?![а-яё])|"
    r"(?<![а-яё])(?:максимум|предел\w*|лимит\w*|потол\w*)(?![а-яё])|≤|<=|"
    r"(?:цел\w*|план\w*|норм\w*|норматив\w*|sla|kpi|таргет\w*)\W+(?:[а-яёa-z]+\W+){0,3}?до\s+\d",
    re.I)
_TEXT_HIGHER = re.compile(
    r"больше\s*[—–-]?\s*лучше|чем\s+больше\b[^.;!?]{0,60}?\bтем\s+лучше|"
    r"(?<![а-яё])не\s+(?:менее|меньше|ниже|хуже)(?![а-яё])|(?<![а-яё])(?:как\s+)?минимум(?![а-яё])|≥|>=",
    re.I)

# ── колонка цели ──────────────────────────────────────────────────────────────────────────────────────────────────────
# («мин» — ещё и минуты: «Цель SLA, мин» ничего о направлении не говорит)
_TARGET_LOWER = re.compile(r"(?<![а-яё])(?:макс\w*|max|предел\w*|лимит\w*|потол\w*|не\s+более|не\s+выше|до)(?![а-яёa-z])|≤|<=",
                           re.I)
_TARGET_HIGHER = re.compile(r"(?<![а-яё])(?:минимум\w*|минимальн\w*|min|не\s+менее|не\s+ниже)(?![а-яёa-z])|≥|>=", re.I)

# ── смысл величины ────────────────────────────────────────────────────────────────────────────────────────────────────
# хорошее, даже когда в имени время или срок: «Решено в первый день», «Доставлено вовремя», «Доступность», «Uptime»
_GOOD = re.compile(
    r"вовремя|в\s+срок|своевремен|решен\w*\s+(?:в|за)\s+перв|с\s+первого|доступност|uptime|аптайм|время\s+работы|"
    r"наработк|срок\s+службы|время\s+(?:на\s+сайте|в\s+приложении|просмотра|чтения|сеанса)|продолжительност\w*\s+жизни|"
    r"(?<![а-яё])(?:nps|csat|enps)(?![а-яё])|удовлетвор|лояльн|конверси|удержани|retention|выручк|прибыл|доход|"
    r"продаж|выполнен\w*|исполнен\w*|успеваем|трудоустро",
    re.I)
_BAD = re.compile(
    r"ошибк|отток|churn|брак|дефект|просроч|опоздан|брошен|жалоб|претензи|возврат\w*|авари|инцидент|(?<![а-яё])сбо[йяеи]|"
    r"отказ\w*|(?<![а-яё])просто[йяе]|downtime|задержк|ожидани|latency|(?<![а-яё])пинг|отклик|"
    r"(?<![а-яё])время\s+(?:ответа|решения|реакции|обработки|доставки|восстановления|загрузки|устранения|ожидания)|"
    r"длительност\w*\s+(?:простоя|ремонта|обработки|решения)|"
    r"затрат|расход|издерж|себестоим|стоимост\w*\s+привлеч|(?<![a-z])cac(?![a-z])|задолжен|(?<![а-яё])долг|убыт|"
    r"(?<![а-яё])потер|штраф|текучест|увольнен|отчислен|выброс|загрязн|(?<![а-яё])дтп(?![а-яё])|преступн|смертн|"
    r"заболеваем|эскалац|переделк|недопостав|дефицит|невыполн|нарушени",
    re.I)
# длительность по единице: «ч», «мин», «дн.», «мс» — у времени решения, срока, задержки меньше — лучше
_TIME_UNIT = re.compile(r"^(?:мин|мин\.|минут\w*|ч|ч\.|час\w*|дн\.?|дн[ейя]+|день|сут\w*|сек\w*|с|мс|ms|s|min|h|hours?|days?)$",
                        re.I)
_TIME_IN_NAME = re.compile(r"[,(]\s*(?:мин|ч|час\w*|дн\.?|дней|сут\w*|сек|мс|ms)\.?\s*\)?\s*$", re.I)


def text_direction(text: Optional[str]) -> Optional[bool]:
    """True — слова автора говорят «меньше — лучше» («не более 2 часов», «максимум 6 ч»), False — «больше —
    лучше» («не менее 80%»), None — не говорят или говорят оба."""
    t = " ".join((text or "").replace(" ", " ").split())
    if not t:
        return None
    lo, hi = bool(_TEXT_LOWER.search(t)), bool(_TEXT_HIGHER.search(t))
    if lo == hi:
        return None
    return lo


def target_direction(target_name: Optional[str]) -> Optional[bool]:
    """Имя колонки цели: «Максимум, ч», «Лимит затрат» — меньше — лучше; «Не менее, %» — больше; иначе None."""
    t = " ".join((target_name or "").split())
    if not t:
        return None
    lo, hi = bool(_TARGET_LOWER.search(t)), bool(_TARGET_HIGHER.search(t))
    if lo == hi:
        return None
    return lo


def name_direction(name: Optional[str], unit: Optional[str] = None, time_unit: Optional[str] = None) -> Optional[bool]:
    """Смысл величины по её имени и единице: True — меньше — лучше (время ответа, срок, затраты, ошибки, отток,
    жалобы), False — больше — лучше (явно хорошее: «вовремя», NPS, выручка), None — не видно."""
    n = " ".join((name or "").split())
    u = " ".join((unit or "").split()).strip(" .") if unit else ""
    if not n and not u:
        return None
    if _GOOD.search(n):
        return False
    if _BAD.search(n):
        return True
    timed = bool(time_unit) or bool(u and _TIME_UNIT.match(u)) or bool(_TIME_IN_NAME.search(n))
    if timed:
        # длительность: время решения, срок поставки, «Цикл сделки, дн.» — меньше — лучше
        return True
    return None


def lower_better(name: Optional[str], unit: Optional[str] = None, *, target_name: Optional[str] = None,
                 text: Optional[str] = None, time_unit: Optional[str] = None) -> tuple[bool, str]:
    """(меньше — лучше?, источник): слова автора о цели → имя колонки цели → смысл величины → «больше — лучше».
    Источник — один из `DIRECTION_SOURCES` (самопроверка верит словам автора, остальное пересчитывает сама)."""
    t = text_direction(text)
    if t is not None:
        return t, "brief"
    g = target_direction(target_name)
    if g is not None:
        return g, "target"
    m = name_direction(name, unit, time_unit)
    if m is not None:
        return m, "name"
    return False, "default"
