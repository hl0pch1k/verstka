class GoalPeriod(BaseModel):
    """Период цели: всё («all»), последний («latest»), диапазон («range»: start…end) или сравнение двух («compare»:
    base — период A или его начало, target — период B или его начало). Периоды — как в данных («2025-06», «2021»)."""

    kind: str = "all"
    start: Optional[str] = None
    end: Optional[str] = None
    base: Optional[str] = None
    target: Optional[str] = None
    # сравнение диапазонов («первое полугодие против второго», «июль против августа–сентября»): концы A и B
    base_end: Optional[str] = None
    target_end: Optional[str] = None


class Goal(BaseModel):
    """Цель из текста: фраза как в тексте, задача, к которой она ведёт, и предмет (основы слов) для сопоставления."""

    phrase: str  # «покажи рост выручки» — с маленькой буквы, как цитата
    task: TaskKind
    viz: VizKind  # к какому виду ведёт
    to: str  # «линейный график» — подпись в интерфейсе
    subject: list[str] = Field(default_factory=list)  # основы слов предмета: ["выручк"]
    metric: list[str] = Field(default_factory=list)  # основы величины после «по»: «по среднему баллу» → ["средн", "балл"]
    at: int = 0  # позиция в тексте
    # цель не выполнима на этом датасете — почему (она не теряется: причина в «Почему так»)
    unmet: Optional[str] = None
    # вопрос: что спрошено — наибольшее/наименьшее («больше всего», «быстрее всех»), итог («сколько всего»), выполнены
    # ли цели и план, порог («выше 80%»), всплеск; None — обычная цель
    ask: Optional[str] = None
    # главное слово величины цели («по свободным местам» → «мест», «удержание клиентов» → «удержан») и отрицания
    # («без НДС» → ["ндс"])
    head: Optional[str] = None
    negate: list[str] = Field(default_factory=list)
    # вопрос понят, а задача — нет («Расскажите о продажах»): показан главный вывод по данным, это сказано
    free: bool = False
    # цель понята снаружи (модель, `verstka/data/intent.py`): поля ниже и вопрос — явные, фразу план не разбирает
    given: bool = False
    column: Optional[str] = None  # колонка-величина, точное имя
    dimension: Optional[str] = None  # колонка-разрез (категории), точное имя
    categories: list[str] = Field(default_factory=list)  # названные строки или колонки («Москва и Казань»)
    weight: Optional[str] = None  # среднее с весом по этой колонке
    period: Optional[GoalPeriod] = None
    # вопросы, на которые отвечает `verstka/data/asks.py`: N крупнейших (`n`), колонка против колонки (`versus` —
    # вторая колонка); колонка-отношение «на единицу», добавленная к таблице (`verstka/data/derive.py`)
    n: Optional[int] = None
    versus: Optional[str] = None
    derive: Optional[dict] = None


