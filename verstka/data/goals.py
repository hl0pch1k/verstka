"""Цели из текста (описание решения §2.3): «покажи рост выручки», «сравни регионы», «из чего складывается выручка»,
«как распределено время ответа», «есть ли связь», «справочно» — и с каким датасетом цель связана.

Цель поднимает свою аналитическую задачу у датасета, о котором она говорит: предмет цели («выручки», «регионы»)
сравнивается с названием файла и колонками по основам слов. Цель без предмета («покажи структуру») относится к любому
датасету, где её задача осуществима. Те же правила (грубее) — у интерфейса (`web/src/ui/create/dataRules.ts`,
`goalsOf`): там цели только показываются, выбор делает сервер."""

from __future__ import annotations

import re
from typing import Iterable, Optional

from pydantic import BaseModel, Field

from verstka.data.words import file_title, stem, stem_in, stems_match
from verstka.data.words import stems_of as _stems_of
from verstka.schemas.data import DatasetProfile, TaskKind, VizKind

__all__ = ["Goal", "goals_of", "stem", "stems_of", "stems_match", "goal_match", "GOAL_VIZ"]

# вид визуализации, к которому ведёт цель (подпись — как в интерфейсе)
GOAL_VIZ: dict[TaskKind, tuple[VizKind, str]] = {
    "dynamics": ("line", "линейный график"),
    "comparison": ("bar", "столбцы"),
    "shares": ("doughnut", "кольцевая диаграмма"),
    "distribution": ("histogram", "гистограмма"),
    "relationship": ("scatter", "точечная диаграмма"),
    "reference": ("table", "таблица"),
    "kpi": ("kpi_cards", "карточки показателей"),
}


class Goal(BaseModel):
    """Цель из текста: фраза как в тексте, задача, к которой она ведёт, и предмет (основы слов) для сопоставления."""

    phrase: str  # «покажи рост выручки» — с маленькой буквы, как цитата
    task: TaskKind
    viz: VizKind  # к какому виду ведёт
    to: str  # «линейный график» — подпись в интерфейсе
    subject: list[str] = Field(default_factory=list)  # основы слов предмета: ["выручк"]
    metric: list[str] = Field(default_factory=list)  # основы величины после «по»: «по среднему баллу» → ["средн", "балл"]
    at: int = 0  # позиция в тексте


_V = r"(?:покажи(?:те)?|показать|отрази(?:те)?|отразить|продемонстрируй(?:те)?|визуализируй(?:те)?)"
_END = r"[^,.;:!?\n]*"
_PATTERNS: list[tuple[TaskKind, re.Pattern[str]]] = [
    ("dynamics", re.compile(
        _V + r"\s+(?:рост|снижени|падени|динамик|изменени|тренд|как\s+(?:рос|рас|меня|измен|пада|сниж))" + _END
        + r"|как\s+(?:росл[аио]?|рос|раст[её]т|растут|менял[аио]?с[ья]|меня[её]тся|меняются|изменял[аио]?с[ья]|"
          r"изменя[её]тся|снижал[аио]?с[ья]|сниж[аеи]ется|снижаются|падал[аио]?|пада[её]т|падают|увеличивал[аио]?с[ья]|"
          r"уменьшал[аио]?с[ья]|сокращал[аио]?с[ья]|выполнял[аио]?с[ья]|исполнял[аио]?с[ья])" + _END
        + r"|динамик[аиуе]\s+" + _END, re.I)),
    ("comparison", re.compile(
        r"(?:сравни(?:те)?|сравнить|сопоставь(?:те)?|сопоставить|сравнение)\s+" + _END
        + r"|(?:кто|какие|какой|какая)(?:\s+[^\s,.;:!?]+){0,2}?\s+(?:лидирует|лидируют|впереди|отста[её]т|отстают)"
        + _END
        + r"|(?:рейтинг|лидер(?:ы|ов)?)\s+" + _END
        + r"|на\s+что\s+(?:уш[её]л|ушла|ушло|ушли|потрачен[аоы]?|тратится|тратятся|тратим|расходуется|пош[её]л|пошла|"
          r"пошли|израсходован[аоы]?)" + _END
        + r"|как\s+(?:исполнен[аоы]?|выполнен[аоы]?)\s+" + _END
        + r"|(?:исполнение|выполнение)\s+(?:бюджета|плана|планов)" + _END, re.I)),
    ("shares", re.compile(
        r"из\s+чего\s+(?:складывается|состоит|складываются|состоят)" + _END
        + r"|" + _V + r"\s+(?:дол[июе]|структур|состав)" + _END
        + r"|(?:что|кто)\s+(?:да[её]т|приносит|формирует|составляет)\s+" + _END
        + r"|структур[ауы]\s+" + _END
        + r"|как\s+(?:устроен[аоы]?|распределя[её]тся|делится|делятся)\s+" + _END, re.I)),
    ("distribution", re.compile(
        r"как\s+распредел[её]н[аоы]?" + _END
        + r"|" + _V + r"\s+(?:распределени|разброс)" + _END
        + r"|(?:распределение|разброс)\s+" + _END, re.I)),
    ("relationship", re.compile(
        r"(?:есть\s+ли\s+связь|связь\s+между|зависит\s+ли|как\s+\S+\s+влия[ею]т|корреляци)" + _END, re.I)),
    ("reference", re.compile(r"(?:справочно|для\s+справки|полный\s+список|перечень|списком)" + _END, re.I)),
    ("kpi", re.compile(r"(?:ключевые\s+(?:показатели|цифры|числа|метрики)|главные\s+(?:цифры|числа)|в\s+цифрах)" + _END,
                       re.I)),
]

# граница придаточного внутри фразы: «что даёт выручку и где узкие места» → «что даёт выручку»
_CLAUSE = re.compile(r"\s+(?:и|а|но)\s+(?=(?:где|как|что|кто|почему|какие|какой|какая|зачем|когда|покажи|сравни|"
                     r"на\s+что|в\s+чём|в\s+чем|за\s+счёт|за\s+счет|из\s+чего)\b)", re.I)

# глаголы изменения и исполнения в любой форме — слова цели, а не предмет («как менялось число клиентов»)
_VERB_WORD = re.compile(r"^(?:из)?меня\w*|^сниж\w*|^рос\w*|^раст\w*|^пада\w*|^увелич\w*|^уменьш\w*|^сокращ\w*|"
                        r"^выполня\w*|^исполня\w*|^вырос\w*", re.I)

# служебные слова и слова самих целей — не предмет
_STOP = frozenset({
    "и", "в", "во", "по", "за", "на", "с", "со", "от", "до", "из", "как", "что", "у", "к", "для", "между", "а", "или", "их",
    "его", "её", "ее", "это", "эти", "этот", "все", "всех", "весь", "наш", "наши", "нашей", "наших", "мы", "где", "ли",
    "есть", "покажи", "покажите", "показать", "отрази", "отразить", "сравни", "сравните", "сравнить", "сопоставь",
    "сопоставить", "сравнение", "рост", "роста", "снижение", "падение", "динамику", "динамика", "динамики", "изменение",
    "изменения", "тренд", "складывается", "состоит", "складываются", "состоят", "доли", "долю", "структуру", "структура",
    "структуры", "состав", "даёт", "дает", "приносит", "формирует", "составляет", "распределено", "распределена",
    "распределены", "распределение", "разброс", "связь", "зависит", "влияет", "корреляция", "справочно", "справки",
    "список", "полный", "перечень", "списком", "ключевые", "показатели", "главные", "цифры", "числа", "метрики",
    "исполнен", "исполнена", "исполнено", "выполнен", "выполнена", "выполнено", "исполнение", "выполнение",
    "устроен", "устроена", "устроено", "устроены", "ушёл", "ушел", "ушла", "ушло", "ушли", "потрачен", "потрачена",
    "тратится", "растёт", "растет", "растут", "делится", "кто", "какие", "какой", "какая", "лидирует", "лидируют", "впереди", "отстаёт", "отстает", "отстают", "рейтинг",
    "лидеры", "лидер", "лидеров", "росла", "рос", "росло", "росли", "менялась", "менялся", "менялись", "изменялась",
    "снижалась", "году", "год", "года", "месяц", "месяцев", "данные", "данных", "файл", "файлах", "приложенных", "цифрах",
    "визуализируй", "продемонстрируй", "самые", "самых", "разные", "разных", "чем", "тем", "насколько", "как",
    "выполнялся", "выполнялась", "исполнялся", "исполнялась",
})
def stems_of(text: str) -> list[str]:
    """Основы значимых слов (без служебных и слов целей), по порядку, без повторов."""
    words = [w for w in re.findall(r"[a-zа-яё0-9]+", (text or "").lower()) if not _VERB_WORD.match(w)]
    return _stems_of(" ".join(words), _STOP)


def _metric_of(phrase_: str) -> list[str]:
    """Величина цели — слова после «по» («сравни классы по среднему баллу» → средн, балл); «по годам», «по
    кварталам» — разрез, а не величина."""
    m = re.search(r"\bпо\s+(.+)$", phrase_, re.I)
    if not m:
        return []
    out = stems_of(m.group(1))
    return [x for x in out if x not in _PERIOD_STEMS]


# разрез («по годам») и служебные слова величины («по числу посетителей» — величина «посетители») — не величина
_PERIOD_STEMS = {"год", "года", "годам", "месяц", "месяцам", "квартал", "кварталам", "недел", "неделям", "дням", "дн",
                 "числ", "количеств", "кол", "объем", "объём"}
# «сравни A по X и B по Y» — две цели: «сравни районы по цене … и школы по среднему баллу»
_SPLIT_AND = re.compile(r"^(?P<verb>(?:сравни(?:те)?|сравнить|сопоставь(?:те)?|сопоставить)\s+)(?P<a>.+?\s+по\s+.+?)\s+и\s+"
                        r"(?P<b>\S+(?:\s+\S+)?\s+по\s+.+)$", re.I)


def goals_of(text: str) -> list[Goal]:
    """Цели в тексте по порядку появления. Одна фраза может дать несколько целей («сравни рост регионов» — и
    сравнение, и динамику); одинаковые фразы одной задачи — один раз."""
    found: list[Goal] = []
    if not text:
        return found
    # придаточные — отдельно: «как менялось число пациентов … и как росли доставки» — две цели
    segs: list[tuple[int, str]] = []
    pos = 0
    for part in _CLAUSE.split(text):
        at = text.find(part, pos)
        segs.append((max(at, 0), part))
        pos = max(at, 0) + len(part)
    for task, rx in _PATTERNS:
        for at0, seg in segs:
            for m in rx.finditer(seg):
                q = " ".join(m.group(0).split()).strip(" -—–")
                if not q:
                    continue
                q = q[0].lower() + q[1:]
                viz, to = GOAL_VIZ[task]
                parts = [q]
                sp = _SPLIT_AND.match(q) if task == "comparison" else None
                if sp:
                    parts = [sp.group("verb") + sp.group("a"), sp.group("verb") + sp.group("b")]
                for k, ph in enumerate(parts):
                    g = Goal(phrase=ph, task=task, viz=viz, to=to, subject=stems_of(ph),
                             metric=_metric_of(ph) if task == "comparison" else [], at=at0 + m.start() + k)
                    if not any(x.task == g.task and x.phrase == g.phrase for x in found):
                        found.append(g)
    found.sort(key=lambda g: (g.at, list(GOAL_VIZ).index(g.task)))
    return found


def goal_match(goal: Goal, profile: DatasetProfile, values: Optional[Iterable[str]] = None) -> float:
    """Насколько цель говорит об этом датасете: название файла (1 за слово), колонки (0,6), значения категорий (0,6).
    Цель без предмета — 0,5 (относится к любому подходящему датасету); предмет не совпал ни с чем — 0."""
    if not goal.subject:
        return 0.5
    names = stems_of(file_title(profile.file, profile.sheet))
    score = 0.0
    used: set[str] = set()
    for s in goal.subject:
        if any(stem_in(s, w) for w in names):
            score += 1.0
            used.add(s)
    col_words = stems_of(" ".join(c.name for c in profile.columns))
    for s in goal.subject:
        if any(stem_in(s, w) for w in col_words):
            score += 0.6
            used.add(s)
    if values:
        val_words = stems_of(" ".join(values))
        for s in goal.subject:
            if s not in used and any(stem_in(s, w) for w in val_words):
                score += 0.6
    return score
