# вводные перед вопросом: «Хотим понять, …», «Главный вопрос — …», «Нужно показать, …», «Важно понять, …»
_LEAD = re.compile(r"^(?:(?:мы\s+)?(?:хотим|хочу|хотелось\s+бы|нужно|надо|важно|необходимо|просим|прошу)\s+"
                   r"(?:понять|показать|узнать|выяснить|найти|увидеть|разобраться|подчеркнуть|проверить|оценить|"
                   r"посмотреть|сравнить|определить)(?:\s*,|\s+(?=что\b|где\b|как\w*\b|кто\b|у\s+как|в\s+как|"
                   r"сколько\b|почему\b|насколько\b|какие\b|ли\b))?|главн(?:ый|ое)\s+(?:вопрос|задача)?\s*(?:—|-|:)|"
                   r"главное\s*(?:—|-|:)|вопрос\s*(?:—|-|:)|задача\s*(?:—|-|:)|интересует,?)\s*", re.I)
# хвост, который не о величине: «… и стоит ли её модернизировать», «…, чтобы разобрать», «… — то есть …»
_TAIL_CUT = re.compile(r"(?:,?\s+и\s+(?:стоит|нужно|надо|можно|следует|имеет\s+смысл)\s+ли\b|,\s*чтобы\b|"
                       r",?\s+и\s+(?:насколько|на\s+сколько|как\s+(?:сильно|быстро))\b|"
                       r"\s+—\s*то\s+есть\b|\s+и\s+правда\s+ли\b|,\s+и\s+).*$", re.I)
_COMPARED = re.compile(r"\s+по\s+сравнению\s+с\s+[^,.;?!]+", re.I)


def strip_lead(text: str) -> str:
    """Вопрос без вводных: «хотим понять, какие специальности оцениваются хуже всего» → «какие специальности …»."""
    t = " ".join((text or "").split())
    m = _LEAD.match(t.lower())
    return t[m.end():].lstrip(" ,—-:") if m and m.end() < len(t) else t


def _metric_text(text: str) -> str:
    """Текст величины цели: без хвоста («и стоит ли …») и базы сравнения («по сравнению с прошлым годом»); после
    «— то есть» — уточнение, оно и есть величина («где не хватает врачей — то есть где на одного врача приходится
    больше всего посещений»)."""
    m = re.search(r"\s+[—–-]\s*то\s+есть\s+(.+)$", text, re.I)
    if m:
        text = m.group(1)
    return _COMPARED.sub("", _TAIL_CUT.sub("", text))


def _sentences(text: str) -> list[tuple[int, str]]:
    out = []
    for m in re.finditer(r"[^.!?…\n]+[.!?…]?", text or ""):
        s = m.group(0).strip()
        if len(s) >= 6:
            out.append((m.start() + (len(m.group(0)) - len(m.group(0).lstrip())), s))
    return out


# целое, по которому спрошено среднее: «по всей платформе», «по заводу в целом»
_WHOLE = r"(?:компании|платформе|району|заводу|клинике|сети|стране|городу|области|школе|больнице|предприятию|региону)\b"
_ADJ_END = re.compile(r"(?:ому|ему|ого|его|ой|ый|ий|ая|яя|ое|ее|ые|ие|ых|их|ым|им|ую|юю|ыми|ими|ей)$")
_GENERIC_HEAD = {"числ", "количеств", "кол", "дол", "уровн", "уровен", "объем", "объ", "показател", "значени", "сумм", "всем",
                 "всех", "перв", "последн"}
_VERBISH = re.compile(r"(?:ется|ится|ются|ятся|ает|яет|ует|еет|ают|яют|уют|ался|ался|ались|илось|алось)$")


def _tail_words(tail: str) -> list[str]:
    out = []
    for w in re.findall(r"[а-яёa-z0-9]+", tail):
        if w in _STOP or w in _QWORDS or len(w) < 2 or re.fullmatch(r"\d+", w):
            continue
        mapped = next((meas for v, meas in _VERB_MEASURE.items() if w.startswith(v)), None)
        if mapped:
            out.append(mapped)
        elif len(w) > 5 and _VERBISH.search(w):
            continue  # глагол («остаётся») — не величина
        else:
            out.append(w)
    return out


def goal_focus(phrase_: str) -> tuple[list[str], Optional[str], list[str]]:
    """(величина, главное слово, отрицания) цели: «сравните тарифы по цене с НДС» → ([цен, ндс], «цен», []);
    «по свободным местам» → ([свободн, мест], «мест», []); «цена без НДС» → отрицание «ндс». Величина — после «какой
    средний», «по» (не «по всем X» и не «по месяцам»), «больше/меньше всего», «самый высокий», глагола изменения;
    главное слово — первое существительное величины (прилагательные и «число», «доля», «уровень» — пропускаются)."""
    low = _metric_text(strip_lead(" ".join((phrase_ or "").lower().replace("ё", "е").split())))
    sm = _SURGE_Q.search(low)
    if sm:
        # «клиенты по отраслям — госсектор выстрелил», «какие сервисы тянут рост — по-моему PaaS быстрее всех»:
        # величина — до слов о рывке, без разреза («по отраслям»); названный сегмент — гипотеза, а не колонка
        low = re.sub(r"\bпо\s+[а-яёa-z]+", " ", low[:sm.start()])
        low = " ".join(w for w in low.split() if w not in ("—", "-", "–")).strip(" ,:")
    negate = [stem(w) for w in re.findall(r"\bбез\s+([а-яёa-z0-9]+)", low)]
    pats = [r"(?:какой|какая|какое|какие|каков\w*)\s+(?:у\s+нас\s+|у\s+вас\s+)?((?:средн|общ|суммарн)\w*\s+.+?)(?:\s+(?:по\s+все[мхй]\b|в\s+целом\b|"
            r"по\s+" + _WHOLE + r").*)?$",
            r"\bпо\s+(?!все[мхй]\b|месяц|недел|дн|квартал|год|сравнению\b|" + _WHOLE + r")(.+)$",
            r"(?:больше|меньше|выше|ниже|лучше|хуже|чаще|реже)\s+(?:всего|всех)\s+(.+)$",
            r"сам(?:ый|ая|ое|ые|ых|ого|ой|ую|ом)\s+[а-яё]+\s+(.+)$",
            r"(?:рост|снижени\w*|падени\w*|динамик\w*|изменени\w*|как\s+(?:\S+\s+)?(?:меня\w*|раст\w*|рос\w*|"
            r"пада\w*|снижа\w*|измен\w*))\s+(.+)$"]
    words: list[str] = []
    for i, pat in enumerate(pats):
        m = re.search(pat, low)
        if m:
            words = _tail_words(m.group(1))
            if words:
                break
    if not words:
        words = _tail_words(low) if any(low.find(v) >= 0 for v in _VERB_MEASURE) else []
        words = [w for w in words if w in _VERB_MEASURE.values()]
    metric = [x for x in dict.fromkeys(stem(w) for w in words) if x not in _PERIOD_STEMS]
    nouns = [w for k, w in enumerate(words) if not (_ADJ_END.search(w) and not re.search(r"(?:ни|ти|ви|си)е$", w)
                                                    and k + 1 < len(words)) and stem(w) not in _GENERIC_HEAD]
    head = stem(nouns[0]) if nouns else None
    if re.search(r"(?:дольше|быстрее|медленнее)\s+(?:всего|всех)|\bдолго\b|\bждут\b|\bожидани|сколько\s+дней|\bсрок",
                 low) and not _GROW_Q.search(low) and not _SURGE_Q.search(low):
        # «где дольше всего ждут решения по заявлению» — величина: срок, а не число заявлений
        head = "срок"
        metric = ["срок"] + [x for x in metric if x != "срок"]
    if re.search(r"(?:как(?:ой|ова?)|средн\w*)\s+(?:у\s+нас\s+)?(?:средн\w*\s+)?рейтинг", low):
        head = "рейтинг"  # «какой средний рейтинг клиники» — средняя оценка, а не ранжирование; «клиники» — целое
        metric = ["рейтинг"]
    tm = re.search(r"\bтеря\w*\s+([а-яё]{4,})", low)
    if tm and tm.group(1) not in _STOP:
        # «правда ли он теряет абонентов» — величина: абоненты (их число падает), а не «потери»
        head = stem(tm.group(1))
        metric = [head]
    _aud = ("аудитор", "зрител", "слушател", "читател")
    if re.search(r"\bаудитор|\bзрител|\bслушател|\bчитател", low) and (head is None or head.startswith(_aud)):
        # «рост аудитории», «больше всего зрителей» — колонка аудитории (MAU, зрители, читатели)
        head = "аудитор"
        metric = ["аудитор"] + [x for x in metric if not x.startswith(_aud)]
    if re.search(r"\bденег\b|\bденьг|\bзатрат|\bтратим", low):
        head = "денег"  # «больше всего денег» — денежная колонка, какой бы она ни была по имени
    return metric, head, negate


def goal_ask(phrase: Optional[str]) -> Optional[str]:
    """Что цель спрашивает сверх задачи: «кто растёт быстрее всех» → "fastest" (темп каждой категории, а не рост
    целого); «какие … выше 80%» → "above:80" (кто за порогом)."""
    low = strip_lead(" ".join((phrase or "").lower().split()))
    if _SURGE_Q.search(low) and not re.search(r"сниж|снизил|пада|упал|сокращ|сократ|дешеве", low):
        return "fastest"  # «госсектор выстрелил», «кто тянет рост» — темп каждой категории
    m = _GROW_Q.search(low)
    if m and re.search(r"быстрее|сильнее", m.group(0)) and not re.search(r"сниж|снизил|пада|упал|сокращ|сократ|дешеве",
                                                                        m.group(0)):
        return "fastest"
    if m and re.search(r"быстрее|сильнее", m.group(0)):
        return "fastest_down"  # «какой сектор сократил потребление сильнее всех» — наибольшее снижение
    if re.search(r"\bхуже\s+(?:всего|всех)|сам(?:ый|ая|ое|ые)\s+плох", low) and (re.match(_Q_WORD + r"\b", low)
                                                                              or _IMPERATIVE.match(low)):
        return "worst"  # «с каким перевозчиком хуже всего» — худший по смыслу величины (задержка — наибольшая)
    th = _THRESH_Q.search(low)
    if th and (re.match(_Q_WORD + r"\b", low) or re.search(r"\b(?:покаж\w*|назов\w*|сколько|где|какие|каких|какой)\b",
                                                             low)):
        # «какие серверы загружены выше 80%» — порог: кто за ним, а не кто первый
        side = "below" if re.match(r"(?:ниже|меньше|менее|не\s+больше)", th.group(0)) else "above"
        return f"{side}:{th.group(1).replace(',', '.')}"
    if re.search(r"(?:как(?:ие|ой|ая)|кто|где|у\s+кого)\s+(?:\S+\s+){0,3}?не\s+(?:выполнил\w*|дотянул\w*|"
                 r"достиг\w*|справил\w*)", low) and re.search(r"план", low):
        return "miss"  # «какие магазины не выполнили план» — кто ниже плана
    if _MEET_Q.search(low) and re.search(r"норм|норматив|цел[иь]|таргет|sla", low) and \
            not re.search(r"\bне\s+(?:уклад|уложил|выполн|достиг|дотянул|справ)", low):
        return "meet"  # «какие линии укладываются в норму по браку» — кто уложился в свою норму
    if re.search(r"сколько\s+всего|сколько\s+(?:\S+\s+){0,2}?(?:за|в)\s+(?:полугоди|год|квартал|месяц)|общ(?:ий|ая|ее)\s+"
                 r"(?:объ[её]м|сумм|итог|выручк)|итого\s+за", low):
        return "total"  # «сколько всего отгрузили за полугодие» — итог, а не кто первый
    if (re.match(_Q_WORD + r"\b", low) or _IMPERATIVE.match(low)) and _LOW.search(low) and not _GROW_Q.search(low):
        return "min"  # «с каким утверждением согласны меньше всего» — ответ о последнем, а не о лидере
    if re.search(r"бросают|бросил|уходят|не\s+дош|не\s+заверш|отказыва", low) and (
            re.match(_Q_WORD + r"\b", low) or _MOST.search(low)):
        return "min"  # «какие курсы бросают чаще всего» — меньше всего завершают
    if re.search(r"\bсредн\w*|\bдол[яиюе]\b|\bпроцент", low) and re.search(r"по\s+все[мйх]\b|в\s+целом|общ(?:ий|ее|ая)|"
                                                                     r"по\s+" + _WHOLE, low):
        return "mean"  # «какой средний NPS по всем продуктам» — одно среднее, а не кто впереди
    if re.search(r"отрыв|разрыв|на\s*сколько|насколько\s+(?:опереж|впереди)", low):
        return "margin"  # «кто победил и с каким отрывом» — отрыв первого от второго
    return None


def _question_goals(sent: str, at: int) -> list[Goal]:
    """Цели из вопроса или утверждения, которые не взяли шаблоны: задача по смыслу фразы, предмет — её слова."""
    raw_low = " ".join(sent.lower().split())
    low = strip_lead(raw_low)  # «Хотим понять, какие …» — вопрос после вводных
    led = low != raw_low
    q = low.rstrip(" ?!.…")
    looks = led or low.endswith("?") or re.match(_Q_WORD + r"\b", low) is not None or _IMPERATIVE.match(low) is not None \
        or re.search(r"\bли\b", low) is not None or re.search(r"\bпровер(?:ь|ьте|ить)\b", low) is not None \
        or re.search(r"[:—–]\s*" + _Q_WORD + r"\b", low) is not None \
        or _SURGE_Q.search(low) is not None
    if not looks:
        return []
    subject = [x for x in stems_of(q) if x not in {stem(w) for w in _QWORDS}]
    metric, head, negate = goal_focus(q)

    def g(task: TaskKind, ask: Optional[str] = None, free: bool = False) -> Goal:
        viz, to = GOAL_VIZ[task]
        return Goal(phrase=q, task=task, viz=viz, to=to, subject=subject, metric=metric if task == "comparison" else [],
                    at=at, ask=ask, head=head, negate=negate, free=free)

    if _REL_Q.search(low):
        return [g("relationship")]
    if _DIST_Q.search(low):
        return [g("distribution")]
    if _GROW_Q.search(low) or goal_ask(low) == "fastest":
        return [g("dynamics", "fastest"), g("comparison", "fastest")]
    if _YESNO_Q.search(low) or re.search(r"(?:пада[её]т|падают|раст[её]т|растут|снижа[её]тся|снижаются|сокраща[её]тся|"
                                         r"увеличива[её]тся|дорожа[её]т|дешеве[её]т)\s*(?:\?|[,.]?\s*провер\w*|$)", low):
        # «снизился ли отток», «выручка на одно место падает? проверь» — ряд по времени и ответ «да/нет»
        return [g("dynamics", "yesno")]
    if _MEET_Q.search(low):
        return [g("kpi" if re.search(r"\bцел[иеь]", low) else "comparison", "meet")]
    th = _THRESH_Q.search(low)
    if th and (re.match(_Q_WORD, low) or re.search(r"\b(?:где|какие|каких|какой)\b", low)):
        side = "below" if re.match(r"(?:ниже|меньше|менее|не\s+больше)", th.group(0)) else "above"
        return [g("comparison", f"{side}:{th.group(1).replace(',', '.')}")]
    if _TREND_Q.search(low):
        return [g("dynamics", "spike" if re.search(r"всплеск|пик|скач", low) else None)]
    if goal_ask(low) == "mean":
        return [g("comparison", "mean")]  # «какая доля доставлена вовремя в целом» — одно среднее, а не структура
    if _SHARE_Q.search(low) and not _MOST.search(low):
        return [g("shares")]
    if _MOST.search(low) or re.search(r"\bгде\b.*\b(?:теря\w*|узк\w*|просед\w*|провал\w*)", low):
        return [g("comparison", "min" if _LOW.search(low) else "max")]
    if _TOTAL_Q.search(low):
        if re.search(r"\bза\s+(?:январ|феврал|март|апрел|ма[йя]|июн|июл|август|сентябр|октябр|ноябр|декабр)\w*", low):
            return [g("dynamics", "total")]  # «сколько всего заработали за ноябрь» — итог месяца по времени
        return [g("comparison", "mean" if goal_ask(low) == "mean" else "total")]
    # понятно, что спрошено, но не какая задача: главный вывод по данным — это сказано в «Почему так»
    return [g("comparison", free=True)] if subject else []


def goal_match(goal: Goal, profile: DatasetProfile, values: Optional[Iterable[str]] = None) -> float:
    """Насколько цель говорит об этом датасете: название файла (1 за слово), колонки (0,6), значения категорий (0,6).
    Цель без предмета — 0,5 (относится к любому подходящему датасету); предмет не совпал ни с чем — 0."""
    if not goal.subject:
        return 0.5
    names = stems_of(file_title(profile.file, profile.sheet))
    score = 0.0
    used: set[str] = set()
    for s in goal.subject:
        if any(stem_in(s, w) for w in names):
            score += 1.0
            used.add(s)
    col_words = stems_of(" ".join(c.name for c in profile.columns))
    for s in goal.subject:
        if any(stem_in(s, w) for w in col_words):
            score += 0.6
            used.add(s)
    if values:
        val_words = stems_of(" ".join(values))
        for s in goal.subject:
            if s not in used and any(stem_in(s, w) for w in val_words):
                score += 0.6
    return score
