import { test } from "node:test";
import assert from "node:assert/strict";
import { altWords } from "./altWords";

const A = (kind: string | null, label: string | null, text: string | null) => ({ kind, label, text, used_in: [] });

test("другая форма: название как у вкладок, довод после тире — с маленькой буквы и без точки в конце", () => {
  assert.deepEqual(altWords(A("table", "таблица", "Таблица позволит выписать рядом f(x) и F(x) для нескольких функций.")),
    { name: "Таблица", text: "позволит выписать рядом f(x) и F(x) для нескольких функций" });
});

test("повтор названия снимается, только когда за ним глагол; иначе фраза остаётся целой", () => {
  assert.deepEqual(altWords(A("table", "таблица", "Компактная таблица «Год — Событие» для быстрого просмотра дат")),
    { name: "Таблица", text: "компактная таблица «Год — Событие» для быстрого просмотра дат" });
  assert.deepEqual(altWords(A("bullets", "список", "Короткий список ключевых вех без визуальной хронологии")),
    { name: "Список", text: "короткий список ключевых вех без визуальной хронологии" });
});

test("«Форма «карточки» позволяет…» — глагол согласуется с названием", () => {
  assert.deepEqual(altWords(A("cards", "карточки", "Форма «карточки» позволяет разделить цель и меры")), { name: "Карточки", text: "позволяют разделить цель и меры" });
});

test("тип диаграммы в начале довода становится названием", () => {
  assert.deepEqual(altWords(A("chart", "диаграмма", "столбчатая диаграмма: График позволит сравнить годы")), { name: "Столбчатая диаграмма", text: "позволит сравнить годы" });
});

test("без названия — только довод с большой буквы; английские слова — по-русски", () => {
  assert.deepEqual(altWords(A(null, null, "use cards for the steps")), { name: "", text: "Use карточки for the steps" });
  assert.deepEqual(altWords(A("big_number", "большое число", "Акцент на формуле как ключевом факте")), { name: "Большое число", text: "акцент на формуле как ключевом факте" });
});
