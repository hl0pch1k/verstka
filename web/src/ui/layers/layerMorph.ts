// Слои колоды в колоде, суженной помощником: что решается по ширине обёртки колоды (меняется только с окном — посреди
// хода не меняется). V2 версии 100 при 1440; при окне около 1280 (тесная колода) V2 не помещается — свои решения.
import { HELPER_COL, SHEET_PAD } from "../deck/layout";

/** «Текст презентации»: ряд шапки без подписи — заголовок 32 px (373) и его зазор 24, зазоры ряда 24 + 24,
 *  «Скопировать» 173, «Изменить» 190, ✕ 40 и их зазоры 16 + 16 (замер: 880 — ровно содержимое листа при 1440, где
 *  подпись сжимается до нуля, как у V2). У́же — у «Скопировать» остаётся значок (−133). */
export const TEXT_ROW = 860;

/** Тесная колода для шапки «Текста презентации». */
export function textTight(wrap: number): boolean {
  return wrap > 0 && wrap - HELPER_COL - SHEET_PAD < TEXT_ROW;
}
