// «Шаблоны» над экраном результата: выбор шаблона ставит галочку для следующей сборки, а открытая презентация остаётся
// на своём (полоса 01 — о ней). Строка под заголовком говорит это прямо и называет, что можно сделать с выбором:
// новая презентация или «Пересобрать на нём» — та же презентация (текст, параметры, данные) на выбранном шаблоне.

export interface DeckPick {
  /** Строка под заголовком раздела. */
  line: string;
  /** Шаблон, на котором можно пересобрать открытую презентацию; null — кнопки нет. */
  rebuild: string | null;
}

/** `deckTpl` — шаблон открытой презентации (исходный, не брендированная копия), `chosen` — выбранный в разделе.
 *  «Улучшить готовую» оформлена по исходному файлу — пересборки на другом шаблоне у неё нет. */
export function deckPick(d: { deckTpl: string; deckName: string; chosen: string | null; chosenName: string | null; improved: boolean }): DeckPick {
  const other = d.chosen && d.chosen !== d.deckTpl ? d.chosen : null;
  const what = d.improved ? "для новой презентации" : "для новой презентации или пересборки этой";
  if (!other) return { line: `Эта презентация — на «${d.deckName}». Другой шаблон — ${what}.`, rebuild: null };
  // шаблон открытой презентации — на полосе 01; строка короче места до «Пересобрать на нём» и в узкой колоде
  return { line: `Выбран «${d.chosenName ?? "шаблон"}» — ${what}.`, rebuild: d.improved ? null : other };
}
