// Перечитывание открытой презентации после изменения (исправление слайда, изображение, «верни как было», правка
// помощника) рядом с открытием другой из «Мои презентации» — без React. Открытая остаётся на экране, пока новая не
// загрузилась (`hold`), поэтому перечитывание, которое пришлось на это время, не теряется, а ждёт: открытие отменили
// (слой закрыли) или оно не удалось — открытая осталась и перечитывается; удалось — ждать нечего.

/** Что делать с перечитыванием презентации `gid`: `open` — открытая сейчас, `asked` — запрошенная последней.
 *  - `none` — открыта другая (или никакая): перечитывать нечего;
 *  - `wait` — поверх неё открывается другая: перечитывание ждёт, чем кончится то открытие;
 *  - `now` — перечитать. */
export function reloadPlan(gid: string, open: string | null, asked: string | null): "none" | "wait" | "now" {
  if (open !== gid) return "none";
  return asked === gid ? "now" : "wait";
}

/** Ждущее перечитывание (`skipped`) запускается, когда открытая презентация `open` снова запрошенная последней
 *  (открытие поверх неё отменили или оно не удалось) — только её собственное. */
export const replayWanted = (skipped: string | null, open: string | null): boolean => !!open && skipped === open;
