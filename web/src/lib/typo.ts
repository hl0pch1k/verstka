// Типографика заголовков, которые переносятся (фазы «Сборки» в две строки, заголовки коробок, названия переключателей):
// короткий предлог, союз или частица не остаётся в конце строки — неразрывный пробел привязывает его к следующему слову
// («Смотрю на слайды», «Сверяю план с текстом», «Проверяю шрифты и цвета»).

/** Короткие слова, которые не остаются в конце строки (предлоги, союзы, частицы). «ли» — нет: она относится к
 *  предыдущему слову («есть ли»), а не к следующему. */
const SHORT = [
  "а", "в", "во", "и", "к", "ко", "о", "об", "обо", "с", "со", "у",
  "без", "да", "для", "до", "за", "из", "или", "на", "над", "не", "ни", "но", "от", "по", "под", "при", "про",
];
/** Привязывается только к слову, числу, открывающей кавычке или скобке; через тире, закрывающую кавычку и прочую
 *  пунктуацию — нет: «план и — текст» остаётся как есть. */
const RE = new RegExp(`(^|[\\s(«„"\\u00a0])(${SHORT.join("|")})[ \\t]+(?=[\\p{L}\\p{N}«„"(])`, "giu");

/** Привязывает короткие слова к следующему неразрывным пробелом. Уже привязанные и длинные слова не трогает. */
export function bindShort(text: string): string {
  // два прохода: подряд идущие короткие слова («и в тексте») — каждое к своему следующему
  let s = text;
  for (let i = 0; i < 2; i++) s = s.replace(RE, (_m, pre: string, word: string) => `${pre}${word} `);
  return s;
}
