// Сообщение об ошибке — только по-русски, без технических хвостов.
//
// Все наши строки неудачи собираются как «<русский префикс>: <причина>» (store.report, flows.ts, api.ts): префикс
// пишем мы, причину приносит сеть или сервер, и она бывает английской («Failed to fetch», «Not Found»,
// «[Errno 28] No space left on device»). Человеку такой хвост ничего не говорит.

/** Есть ли в тексте хоть одна русская буква. */
export const hasCyrillic = (text: string): boolean => /[а-яё]/i.test(text);

/** Сообщение без нерусских частей. Берётся первая непустая строка (сервер дописывает трассировку), она делится по
 *  «: » на части, части без русских букв отбрасываются, остальные склеиваются в прежнем порядке:
 *  «Шаблон разобран, но не загрузился: Сеть недоступна: Failed to fetch» → «Шаблон разобран, но не загрузился: Сеть
 *  недоступна». Чисто русский текст не меняется. Если русского не осталось («OSError: [Errno 28] …»), возвращается
 *  `fallback`. */
export function humanError(text: string | null | undefined, fallback = "Не получилось. Попробуйте ещё раз."): string {
  const first = (text ?? "").split("\n").map((l) => l.trim()).find(Boolean) ?? "";
  const kept = first.split(/:\s+/).map((s) => s.trim()).filter(hasCyrillic);
  return kept.length ? kept.join(": ") : fallback;
}
