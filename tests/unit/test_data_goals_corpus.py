@pytest.mark.parametrize("phrase,task,st,metric", _cases())
def test_template_phrasings_are_parsed(phrase, task, st, metric):
    gs = goals_of(phrase)
    assert gs, phrase
    g = next((x for x in gs if x.task == task), None)
    assert g is not None, (phrase, [(x.task, x.phrase) for x in gs])
    assert any(s.startswith(st[:4]) or st.startswith(s[:4]) for s in g.subject), (phrase, g.subject)
    if metric:
        assert any(s.startswith(st[:4]) for s in g.metric), (phrase, g.metric)


@pytest.mark.parametrize("phrase,task,st", NATURAL)
def test_natural_phrasings_are_parsed(phrase, task, st):
    gs = goals_of(phrase)
    assert gs, phrase
    g = next((x for x in gs if x.task == task), None)
    assert g is not None, (phrase, [(x.task, x.phrase, x.free) for x in gs])
    words = g.subject + g.metric + ([g.head] if g.head else [])
    assert any(w.startswith(st[:4]) or st.startswith(w[:4]) for w in words), (phrase, words)


def test_corpus_is_large():
    assert len(_cases()) + len(NATURAL) >= 150


def test_focus_head_qualifiers_and_negation():
    assert goal_focus("сравните тарифы по цене с ндс") == (["цен", "ндс"], "цен", [])
    m, h, n = goal_focus("сравните тарифы по цене без ндс")
    assert h == "цен" and n == ["ндс"]
    assert goal_focus("сравните продукты по свободным местам")[:2] == (["свободн", "мест"], "мест")
    assert goal_focus("какой средний nps по всем продуктам")[1] == "nps"
    assert stem("свободным") == stem("свободно") == "свободн"


def test_unrecognised_question_is_kept_as_a_free_goal():
    gs = goals_of("Расскажите про наши дела во втором квартале.")
    assert gs and gs[0].free
    assert not goals_of("Данные — в приложенных файлах.")  # не вопрос и не просьба — не цель
