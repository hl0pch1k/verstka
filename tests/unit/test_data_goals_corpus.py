def _cases() -> list[tuple[str, str, str, bool]]:
    out = []
    for sg, pl, dat_pl, nom, gen, dat, st in DOMAINS:
        for tpl, task, metric in TEMPLATES:
            out.append((tpl.format(sg=sg, pl=pl, dat_pl=dat_pl, nom=nom, gen=gen, dat=dat), task, st, metric))
    return out


