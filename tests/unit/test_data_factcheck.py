def corpus_conv3() -> list[tuple[str, list[tuple[str, bytes]], str, str]]:
    """40 таблиц третьей проверки сходимости (`scratchpad/s2/conv3/gen.py`): CSV (с BOM и без), XLSX (объединённые
    ячейки, даты, двухуровневые шапки) и TXT — байтами, как файлы; ключ «27» — три файла под одной целью. Генератор
    перенесён как есть, только запись — в память. Возвращает (ключ, [(имя, байты)], цель-вопрос A, цель B)."""
    import datetime as dt
    import io

    import openpyxl
    from openpyxl.styles import Alignment  # noqa: F401 — генератор выравнивает ячейки шапки

    files_: dict[str, bytes] = {}

    def csv(name, lines, enc="utf-8", bom=False):
        b = ("\n".join(lines) + "\n").encode(enc)
        files_[name] = (b"\xef\xbb\xbf" + b) if bom else b

    def _save(wb, name):
        buf = io.BytesIO()
        wb.save(buf)
        files_[name] = buf.getvalue()

    def xlsx(name, rows, merges=(), fmts=None, sheet="Лист1"):
        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = sheet
        for r in rows:
            ws.append(r)
        for m in merges:
            ws.merge_cells(m)
        for (cell, fmt) in (fmts or {}).items():
            ws[cell].number_format = fmt
        _save(wb, name)
        return wb

    BRIEFS = {}

    # 01 облако: длинный формат, UTF-8 с BOM (Excel «CSV UTF-8»)
    months = ["Январь 2026", "Февраль 2026", "Март 2026", "Апрель 2026", "Май 2026", "Июнь 2026"]
    cs_v = [182400, 176900, 191300, 188700, 203500, 210100]
    k8_v = [64800, 71200, 79500, 88100, 97600, 108300]
    db_v = [41200, 40800, 42900, 43300, 44100, 45000]
    cs_c = [v * 8 for v in cs_v]
    k8_c = [v * 9.5 for v in k8_v]
    db_c = [v * 14 for v in db_v]
    st_c = [212300, 219800, 228400, 236900, 251200, 262700]


    def rub(x):
        s = f"{x:,.0f}".replace(",", " ")
        return s


    lines = ["Период;Сервис;vCPU-часы;Стоимость, ₽"]
    for i, m in enumerate(months):
        lines.append(f"{m};Облачные серверы;{rub(cs_v[i])};{rub(cs_c[i])}")
        lines.append(f"{m};Managed Kubernetes;{rub(k8_v[i])};{rub(k8_c[i])}")
        lines.append(f"{m};Облачные базы данных;{rub(db_v[i])};{rub(db_c[i])}")
