def _stem4(w: str) -> str:
    w = w.lower().replace("ё", "е")
    return w[:min(5, len(w) - 1)] if len(w) > 3 else w


def _prefix(goal: str, name: str) -> int:
    """Самый длинный общий префикс слова цели и слова колонки: «открываемость» ближе к «Открываемость, %», чем к
    «Открыто» (у обоих «откр»)."""
    gw = [w for w in re.findall(r"[а-яёa-z]+", goal.lower()) if len(w) >= 4 and w not in T_STOP]
    nw = re.findall(r"[а-яёa-z]+", name.lower())
    return max((len(os.path.commonprefix([g, n])) for g in gw for n in nw), default=0)


def _hits(goal: str, name: str) -> int:
    gw = [_stem4(w) for w in re.findall(r"[а-яёa-z]+", goal.lower()) if len(w) >= 4 and w not in T_STOP]
    nw = [_stem4(w) for w in re.findall(r"[а-яёa-z]+", name.lower()) if len(w) >= 3]
    return sum(1 for g in gw if any(min(len(g), len(n)) >= 3 and (g.startswith(n) or n.startswith(g)) for n in nw))


class Raw:
    """Сырые строки таблицы глазами теста."""

    def __init__(self, t: Table, prof):
        self.t, self.prof = t, prof
        self.title = re.sub(r"\.[a-z]+$", "", t.file)
        n = len(t.rows)
        tot = set(t.totals or []) | {i for i, r in enumerate(t.rows) if any(isinstance(v, str) and TOTAL_LAB.match(
            v.strip()) for v in r[:2])}
        bench = {i: " ".join(str(r[k]).split()) for i, r in enumerate(t.rows) if i not in tot
                 for k in range(min(2, len(r))) if isinstance(r[k], str) and BENCH_LAB.match(" ".join(r[k].split()))}
        self.bench = bench if n - len(tot) - len(bench) >= 2 else {}
        self.tot_rows = sorted(tot)
        self.rows = [i for i in range(n) if i not in tot and i not in self.bench]
        self.cols = [c.name for c in prof.columns]
        self.units = [c.unit for c in prof.columns]
        self.types = [c.type for c in prof.columns]
        self.roles = [c.role for c in prof.columns]
        self.num: dict[int, list[Optional[float]]] = {}
        for j, c in enumerate(prof.columns):
            if c.role == "metric":
                vals = [_raw(r[j]) if j < len(r) else None for r in t.rows]
                if any(vals[i] is not None for i in self.rows):
                    self.num[j] = vals

    def col(self, name: str) -> Optional[int]:
        base = re.sub(r"\s*,[^,]*$", "", name).strip()
        for j, c in enumerate(self.cols):
            if c == name or c == base or re.sub(r"\s*,[^,]*$", "", c).strip() == base:
                return j
        return None

    def vals(self, j: int) -> list[float]:
        return [v for v in (self.num[j][i] for i in self.rows) if v is not None]

    def text(self, i: int, j: int) -> str:
        v = self.t.rows[i][j] if j < len(self.t.rows[i]) else None
        if v is None:
            return ""
        if isinstance(v, float) and v.is_integer():
            v = int(v)
        return " ".join(str(v).split())

    def total_col(self) -> Optional[int]:
        tc = getattr(self.prof, "total_column", None)
        if tc and self.col(tc) is not None:
            return self.col(tc)
        return next((j for j in self.num if TOTAL_LAB.match(self.cols[j])), None)

    def sums_match(self, j: int) -> bool:
        """Итог в таблице равен сумме: строка «Итого», колонка «Всего» как сумма частей или строки по 100."""
        s = sum(self.vals(j))
        for i in self.tot_rows:
            tv = _raw(self.t.rows[i][j]) if j < len(self.t.rows[i]) else None
            if tv is not None and s and abs(tv - s) <= max(0.51, 0.005 * abs(s)):
                return True
        tj = self.total_col()
        if tj is not None:
            if j == tj:
                return True
            parts = [k for k in self.num if k != tj and (self.units[k] or "") == (self.units[tj] or "")
                     and not CHANGE_COL.search(self.cols[k])]
            if j in parts and all(abs(sum(self.num[k][i] or 0 for k in parts) - (self.num[tj][i] or 0)) <= 0.51
                                  for i in self.rows):
                return True
        return False

    def additive(self, j: int) -> bool:
        name, unit = self.cols[j], (self.units[j] or "").strip()
        if re.match(r"(?i)просто[йия]|сверхурочн|отработан", name.strip()):
            return True  # простои и сверхурочные часы за период — накопленное время, складываются
        if unit == "%" or self.types[j] == "percent":
            return False
        if T_LEVEL_UNIT.search(unit) or T_LEVEL_NAME.search(name) or name.strip().upper() in T_CURRENCY:
            return False
        if self.sums_match(j):
            return True
        if T_COUNT_UNIT.match(unit) or T_FLOW.search(name):
            return True
        if not unit and re.fullmatch(r"[А-ЯЁ]{2,5}", name.strip()) and self.vals(j) and \
                all(float(v).is_integer() for v in self.vals(j)):
            return True  # «ДТП», «ЧС» целыми числами — число случаев (раунд 7, C4)
        if not unit and re.match(r"^[А-ЯЁ][а-яё]+(?:ено|ано|ято|ыто|ито|уто)\s+[а-яё]+", name.strip()) and self.vals(j) \
                and all(float(v).is_integer() for v in self.vals(j)):
            return True  # «Куплено мест», «Продано билетов» целыми — счёт
        if not unit and re.fullmatch(r"[А-ЯЁ][а-яё]+(?:ов|ев|ей|ий)", name.strip()) and self.vals(j) \
                and all(float(v).is_integer() and v >= 0 for v in self.vals(j)):
            return True  # «Рейсов», «Возвратов», «Заказов» целыми — счёт
        if re.fullmatch(r"(?i)(?:абонент|клиент|пользовател|сотрудник|подписчик)[ыи]|ваканси[ия]|штат", name.strip()):
            return True  # «Абоненты», «Клиенты», «Вакансии», «Штат» — счёт людей и мест
        if re.fullmatch(r"(?:пн|вт|ср|чт|пт|сб|вс|(?:19|20)\d\d)", name.strip().lower()) and T_FLOW.search(self.title):
            return True  # колонка-день или колонка-год о величине не говорит: «Заказы ресторана по часам» — счёт
        if T_LEVEL_TITLE.search(self.title):
            return False
        return bool(T_MONEY.search(unit))

    def metrics(self) -> list[int]:
        return [j for j in self.num if not CHANGE_COL.search(self.cols[j]) and self.roles[j] == "metric"]

    def expected_metric(self, goal: Optional[str], task: str) -> Optional[int]:
        """Величина вывода по таблице: названная целью; для сравнения — колонка-итог; иначе поток денег; иначе —
        не определена (тогда проверяется только арифметика заявленной колонки)."""
        ms = self.metrics()
        rate = [j for j in ms if re.search(r"на\s+(?:1\s*000|1000|100\s*тыс|100\s*000|душу|человека|жителя)",
                                            self.cols[j] + " " + (self.units[j] or ""), re.I)]
        if goal and rate and re.search(r"обеспеченн|уровн|на душу|на человека", goal, re.I):
            return rate[0]  # «по уровню преступности», «по обеспеченности врачами» — величина на душу
        if goal:
            # одинаковые имена, разные единицы («Экспорт, т» и «Экспорт, $»): «по объёму» — натуральная, «в деньгах» — $
            vol = re.search(r"объ[её]м|тонн|натур|вес\b|штук|литр", goal, re.I)
            mon = re.search(r"выручк|деньг|денеж|стоимост|доллар|рубл", goal, re.I)
            if vol and not mon:
                tw = [j for j in ms if re.search(r",\s*(?:т|кг|л|шт\.?|м³)$", self.cols[j])]
                if tw:
                    return tw[0]
        if goal and re.search(r"быстрее|медленнее|дольше|скорост|\bждут\b|ожидани", goal, re.I) and \
                not re.search(r"дорожа|дешеве|раст|рост", goal, re.I):
            # «кто обрабатывает заказы быстрее», «где дольше ждут» — время, а не число заказов и не «доля в срок»
            dur = [j for j in ms if (self.units[j] or "").strip() != "%" and (
                re.match(r"(?i)\s*(?:средн\w*\s+)?(?:врем|срок|длительн)", self.cols[j])
                or (self.units[j] or "").strip() in ("мин", "мин.", "ч", "ч.", "дн.", "дн", "с", "сек", "мс"))]
            if dur:
                return dur[0]
        if goal:
            # цель называет величину своими словами
            low = goal.lower().replace("ё", "е")
            pick = None
            per = re.search(r"на\s+(?:одного\s+|1\s+)?([а-я]{4})", low)
            if per:
                # «нагрузка на одного врача» — колонка «… на врача»
                pick = next((j for j in ms if re.search(r"\bна\s+(?:одного\s+|1\s+)?" + per.group(1), self.cols[j].lower())),
                            None)
            if pick is None and re.search(r"загруж|нагрузк", low):
                vis = [j for j in ms if re.search(r"посещен|нагрузк|загрузк", self.cols[j].lower())]
                pick = next((j for j in vis if not re.search(r"\bна\s", self.cols[j].lower())), vis[0] if vis else None)
            if pick is None and re.search(r"\bденег\b|\bденьг|\bзатрат", low):
                pick = (self.total_col() if task == "comparison" else None) or next(
                    (j for j in ms if T_MONEY.search(self.units[j] or "")), None)
            if pick is None and re.search(r"(?:средн\w*|как\w*)\s+рейтинг", low):
                pick = next((j for j in ms if re.search(r"оценк|балл|рейтинг", self.cols[j].lower())), None)
            if pick is None and re.search(r"средн\w*\s+(?:процент|дол)", low):
                pick = next((j for j in ms if (self.units[j] or "").strip() == "%"), None)
            if pick is None and re.search(r"\bуход|\bуходит|\bушл", low):
                # «стало ли меньше уходить абонентов» — отток, а не число абонентов
                pick = next((j for j in ms if re.match(r"(?i)\s*отток", self.cols[j])), None) or next(
                    (j for j in ms if re.match(r"(?i)\s*ушл|\s*ушедш", self.cols[j])), None)
            if pick is None and re.search(r"(?:вы|ис)полнени\w*\s+плана", low):
                # «с выполнением плана» — колонка исполнения («Выполнение, %»), если она есть, а не «План»
                pick = next((j for j in ms if re.match(r"(?i)\s*(?:вы|ис)полнени|%\s*плана", self.cols[j])), None)
            if pick is None and re.search(r"отклонени", low):
                dev = [j for j in ms if re.match(r"(?i)\s*отклонени", self.cols[j])]
                pick = next((j for j in dev if (self.units[j] or "").strip() == "%"), dev[0] if dev else None)
            if pick is not None:
                return pick
        if goal:
            hits = [_hits(goal, self.cols[j]) for j in ms]
            if hits and max(hits) > 0:
                tied = [j for j, h in zip(ms, hits) if h == max(hits)]
                # «с НДС» — не «без НДС», «без НДС» — только «без»
                neg = re.search(r"\bбез\s+(\w+)", goal, re.I)
                pos = re.search(r"\bс\s+(\w+)", goal, re.I)
                if neg:
                    tied = [j for j in tied if re.search(r"\bбез\b", self.cols[j], re.I)] or tied
                elif pos:
                    tied = [j for j in tied if not re.search(r"\bбез\b", self.cols[j], re.I)] or tied
                if re.search(r"итог", goal, re.I):
                    tied = [j for j in tied if re.search(r"итог|всего", self.cols[j], re.I)] or tied
                best = max(_prefix(goal, self.cols[j]) for j in tied)
                if best >= 7 and not re.search(r"конверс|доле|доли|долю|процент|средн|оценк", goal, re.I):
                    # слово цели целиком в имени колонки — она и названа («открываемость», а не «Открыто»)
                    tied = [j for j in tied if _prefix(goal, self.cols[j]) == best]
                # равные по словам цели: «по конверсии», «по доле» — процент; иначе («структура выплат») — деньги,
                # потом то, что складывается
                # норма и цель — ориентир, а не величина («укладываются в норму по браку» — брак)
                tied = [j for j in tied if not re.match(r"(?i)\s*(?:норм|норматив|цел[ья]|таргет)", self.cols[j])] or tied
                base_ = {re.sub(r"\s*,.*$", "", self.cols[j]).strip().lower() for j in tied}
                rate_ = [j for j in tied if (self.units[j] or "").strip() in ("ppm", "‰", "%")]
                if len(base_) == 1 and rate_ and len(rate_) < len(tied) and \
                        not re.search(r"сколько|штук|количеств|число", goal, re.I):
                    return rate_[0]  # «Брак, шт.» и «Брак, ppm»: «по браку», «уровень брака» — уровень (ppm)
                if re.search(r"конверс|доле|доли|долю|процент|средн|оценк", goal, re.I):
                    tied.sort(key=lambda j: (not (self.units[j] == "%" or self.types[j] == "percent"), j))
                else:
                    tied.sort(key=lambda j: (not (T_MONEY.search(self.units[j] or "") and self.additive(j)),
                                             not self.additive(j), j))
                return tied[0]
        tj = self.total_col()
        if task in ("comparison", "shares") and tj is not None:
            return tj  # колонка-итог при колонках-периодах: доли и сравнение — по ней, а не по первому кварталу
        money = [j for j in ms if T_MONEY.search(self.units[j] or "") and self.additive(j)]
        if not money:  # деньги без единицы (выгрузка 1С): по названию
            money = [j for j in ms if re.search(r"выручк|доход|продаж|оборот", self.cols[j], re.I) and self.additive(j)]
        years = [(int(y.group(0)), j) for j in money if (y := re.search(r"(?:19|20)\d\d", self.cols[j]))]
        if len(years) >= 2 and len(years) == len(money):
            return max(years)[1]  # колонки-периоды («Выручка 2025 · Выручка 2026») — последний период
        return money[0] if money else None

    def dims(self) -> list[int]:
        out = [j for j, c in enumerate(self.prof.columns) if c.role in ("dimension", "text", "id")
               and len({self.text(i, j) for i in self.rows} - {""}) >= 2]
        for child, parent in getattr(self.prof, "hierarchies", []) or []:
            pj = self.cols.index(parent) if parent in self.cols else None
            if pj is not None and pj not in out:
                out.append(pj)
        return out

    def by_cat(self, dj: int, j: int, add: bool) -> dict[str, float]:
        labs = [self.text(i, dj) for i in self.rows if self.text(i, dj)]
        # сумма по категории с повторами без строки-опечатки (×100 медианы и больше половины всей суммы)
        typo = set(_dominant_typo(self, j)) if add and len(set(labs)) < len(labs) else set()
        groups: dict[str, list[float]] = {}
        for i in self.rows:
            lab, v = self.text(i, dj), self.num[j][i]
            if lab and v is not None and i not in typo:
                groups.setdefault(lab, []).append(v)
        return {k: (sum(v) if add else sum(v) / len(v)) for k, v in groups.items()}


def _close(a: float, b: float, rel: float = 0.006, absol: float = 0.51) -> bool:
    return abs(a - b) <= max(absol, rel * max(abs(a), abs(b)))


def _shown(fact: float, true: float) -> bool:
    """Число, как его пишет вывод: процент от 10 — целым, меньше — с десятыми; остальное — до двух знаков."""
    a = abs(true)
    for d in (0, 1, 2):
        if abs(round(a, d) - abs(fact)) < 1e-9:
            return True
    return abs(abs(fact) - a) <= 1e-6


def _pct_shown(fact: float, pct: float) -> bool:
    a = abs(pct)
    want = float(round(a)) if a >= 9.95 else round(a, 1)
    return abs(abs(fact) - want) < 1e-6 or (a < 1 and abs(abs(fact) - a) < 0.01)


def _labels(t: Table, prof=None, specs: Optional[dict] = None) -> list[str]:
    """Имена в таблице и на графике (подписи, названия колонок и их числа — «2026» в «Выручка 2026», единицы — «100» в
    «л/100 км», коды-подписи — «404», подписи оси — «нед. 18, 2025»): их цифры — имена, а не числа вывода."""
    out = list(t.columns) + [w for c in t.columns for w in re.findall(r"\d+(?:[\s\u00a0]\d{3})*", c)] + \
        [t.file, re.sub(r"\.\w+$", "", t.file)]
    out += [u for u in (t.units or []) if u]
    roles = [c.role for c in prof.columns] if prof is not None else []
    for r in t.rows:
        out += [str(v) for v in r if isinstance(v, str)]
        out += [str(int(v)) for j, v in enumerate(r) if isinstance(v, (int, float)) and not isinstance(v, bool)
                and j < len(roles) and roles[j] not in ("metric", "id") and float(v).is_integer()]
        # (номера строк «1…250» — не имена: «1» внутри «1 991» — не подпись)
    for b in (specs or {}).values():
        if isinstance(b, ChartSpec):
            out += [str(c) for c in b.categories] + [x.name for x in b.series if x.name] + [b.y_title or ""]
            out += [lower_first_(x.name) for x in b.series if x.name] + [lower_first_(b.y_title or "")]
    # даты и периоды таблицы словами («ноябрь 2025», «6 октября 2025», «2025 год») — имена периода, а не числа
    for r in t.rows:
        for v in r:
            if isinstance(v, str):
                out += _period_words(v)
    out += [x[:1].upper() + x[1:] for x in out if x]  # «Ул. Садовая, 3» в начале заголовка — та же подпись
    return [x for x in out if x]


_MON_NOM = ["январь", "февраль", "март", "апрель", "май", "июнь", "июль", "август", "сентябрь", "октябрь", "ноябрь",
            "декабрь"]
_MON_GEN = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября",
            "декабря"]


def _period_words(v: str) -> list[str]:
    m = re.fullmatch(r"\s*((?:19|20)\d\d)(?:-(\d\d)(?:-(\d\d))?)?\s*", v)
    if not m:
        return []
    y, mo, d = m.groups()
    out = [y, f"{y} год", f"{y} года", f"{y} году"]
    if mo and 1 <= int(mo) <= 12:
        out += [f"{_MON_NOM[int(mo) - 1]} {y}", f"{_MON_GEN[int(mo) - 1]} {y}"]
        if d:
            out.append(f"{int(d)} {_MON_GEN[int(mo) - 1]} {y}")
    return out


def lower_first_(s: str) -> str:
    return s[:1].lower() + s[1:] if s else s


def _claimed(explain: str) -> Optional[str]:
    m = re.search(r"по колонке «([^»]+)»", explain or "")
    return m.group(1) if m else None


